def 判断收率是否合格(收率, 合格线=90.5):
    """
    根据收率判断批次是否合格。
    参数：
        收率：float，本批次的收率值。
        合格线：float，合格的最低标准，默认为 90.5。
    返回：
        "合格" 或 "不合格"
    """
    if 收率 >= 合格线:
        return "合格"
    else:
        return "不合格"


def 统计合格率(所有记录):
    """
    统计所有批次的合格率。
    参数：
        所有记录：list，由 data.读取所有记录() 返回的列表，每个元素是 [批号, 收率, 结果]。
    返回：
        总批数, 合格批数, 合格率(百分数)
    """
    总批数 = len(所有记录)
    if 总批数 == 0:
        return 0, 0, 0.0

    合格批数 = 0
    for 一行 in 所有记录:
        if 一行[2] == "合格":
            合格批数 += 1

    合格率 = (合格批数 / 总批数) * 100
    return 总批数, 合格批数, 合格率
